do $$
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'storage'
      and tablename = 'objects'
      and policyname = 'workspace_members_manage_creatives'
  ) then
    create policy workspace_members_manage_creatives
      on storage.objects
      for all
      to authenticated
      using (
        bucket_id = 'performance-creatives'
        and public.is_workspace_member()
      )
      with check (
        bucket_id = 'performance-creatives'
        and public.is_workspace_member()
      );
  end if;
end;
$$;

