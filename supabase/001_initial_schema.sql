-- Taiom Performance — estrutura inicial do Supabase
-- Seguro para reexecução: cria apenas o que ainda não existe.

create extension if not exists pgcrypto;

create table if not exists public.workspace_members (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text,
  role text not null default 'member' check (role in ('owner', 'member')),
  created_at timestamptz not null default now()
);

create table if not exists public.clients (
  id text primary key,
  name text not null,
  initials text not null,
  meta_budget numeric(12,2),
  google_budget numeric(12,2),
  has_google boolean not null default false,
  tracks_followers boolean not null default false,
  tracks_youtube boolean not null default false,
  default_meta_metrics text[] not null default '{}',
  default_google_metrics text[] not null default '{}',
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.weeks (
  id uuid primary key default gen_random_uuid(),
  client_id text not null references public.clients(id) on delete cascade,
  reference_date date not null,
  period_start date,
  period_end date,
  notes text not null default '',
  source text not null default 'historical' check (source in ('historical', 'csv', 'manual')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (client_id, reference_date),
  check (period_start is null or period_end is null or period_end >= period_start)
);

create table if not exists public.weekly_metrics (
  id bigint generated by default as identity primary key,
  week_id uuid not null references public.weeks(id) on delete cascade,
  platform text not null check (platform in ('meta', 'google')),
  metric_key text not null,
  value numeric,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (week_id, platform, metric_key)
);

create table if not exists public.actions (
  id uuid primary key default gen_random_uuid(),
  week_id uuid not null references public.weeks(id) on delete cascade,
  title text not null,
  details text not null default '',
  done boolean not null default false,
  position integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.metric_strategies (
  id bigint generated by default as identity primary key,
  client_id text not null references public.clients(id) on delete cascade,
  platform text not null check (platform in ('meta', 'google')),
  effective_from date not null,
  metric_keys text[] not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (client_id, platform, effective_from),
  check (cardinality(metric_keys) > 0)
);

create table if not exists public.creatives (
  id uuid primary key default gen_random_uuid(),
  week_id uuid not null unique references public.weeks(id) on delete cascade,
  instagram_url text,
  storage_path text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (instagram_url is not null or storage_path is not null)
);

create index if not exists weeks_client_date_idx
  on public.weeks (client_id, reference_date desc);
create index if not exists weekly_metrics_week_idx
  on public.weekly_metrics (week_id, platform);
create index if not exists actions_week_idx
  on public.actions (week_id, position);
create index if not exists metric_strategies_lookup_idx
  on public.metric_strategies (client_id, platform, effective_from desc);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

do $$
declare
  target_table text;
begin
  foreach target_table in array array['clients', 'weeks', 'weekly_metrics', 'actions', 'metric_strategies', 'creatives']
  loop
    if not exists (
      select 1 from pg_trigger
      where tgname = 'set_updated_at_' || target_table
    ) then
      execute format(
        'create trigger %I before update on public.%I for each row execute function public.set_updated_at()',
        'set_updated_at_' || target_table,
        target_table
      );
    end if;
  end loop;
end;
$$;

create or replace function public.is_workspace_member()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1
    from public.workspace_members
    where user_id = auth.uid()
  );
$$;

revoke all on function public.is_workspace_member() from public;
grant execute on function public.is_workspace_member() to authenticated;

alter table public.workspace_members enable row level security;
alter table public.clients enable row level security;
alter table public.weeks enable row level security;
alter table public.weekly_metrics enable row level security;
alter table public.actions enable row level security;
alter table public.metric_strategies enable row level security;
alter table public.creatives enable row level security;

do $$
declare
  target_table text;
begin
  if not exists (
    select 1 from pg_policies
    where schemaname = 'public'
      and tablename = 'workspace_members'
      and policyname = 'members_read_own_membership'
  ) then
    create policy members_read_own_membership
      on public.workspace_members
      for select
      to authenticated
      using (user_id = auth.uid());
  end if;

  foreach target_table in array array['clients', 'weeks', 'weekly_metrics', 'actions', 'metric_strategies', 'creatives']
  loop
    if not exists (
      select 1 from pg_policies as p
      where p.schemaname = 'public'
        and p.tablename = target_table
        and p.policyname = 'workspace_members_all'
    ) then
      execute format(
        'create policy workspace_members_all on public.%I for all to authenticated using (public.is_workspace_member()) with check (public.is_workspace_member())',
        target_table
      );
    end if;
  end loop;
end;
$$;

